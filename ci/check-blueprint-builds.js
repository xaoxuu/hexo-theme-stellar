#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const THEME_ROOT = path.resolve(__dirname, "..");
const HOST_ROOT = path.resolve(process.argv[2] || path.join(THEME_ROOT, "../.."));
const HEXO = path.join(HOST_ROOT, "node_modules", ".bin", "hexo");
const BLUEPRINTS = ["classic", "minimal-reading", "docs-reference", "light-and-shadow"];

function run(cwd, args) {
  const result = spawnSync(HEXO, args, {
    cwd,
    encoding: "utf8",
    env: { ...process.env, HEXO_READY: "" }
  });
  if (process.env.STELLAR_BLUEPRINT_DEBUG === "1") {
    process.stderr.write(result.stdout || "");
    process.stderr.write(result.stderr || "");
  }
  if (result.status !== 0) {
    process.stderr.write(result.stdout || "");
    process.stderr.write(result.stderr || "");
    throw new Error(`${args.join(" ")} failed with exit code ${result.status}`);
  }
  return result.stdout;
}

function writeSiteSkeleton(directory) {
  const hostPackage = require(path.join(HOST_ROOT, "package.json"));
  const hostHexoVersion = require(path.join(HOST_ROOT, "node_modules", "hexo", "package.json")).version;
  fs.writeFileSync(path.join(directory, "package.json"), `${JSON.stringify({
    private: true,
    hexo: { version: hostHexoVersion },
    dependencies: {
      hexo: hostHexoVersion,
      "hexo-generator-index": hostPackage.dependencies["hexo-generator-index"],
      "hexo-renderer-marked": hostPackage.dependencies["hexo-renderer-marked"]
    }
  }, null, 2)}\n`);
  fs.writeFileSync(path.join(directory, "_config.yml"), [
    "title: Stellar Blueprint Test",
    "subtitle: Generated by the M3 integration gate",
    "url: https://example.com",
    "root: /",
    "permalink: blog/:year/:month/:day/:title/",
    "theme: stellar",
    ""
  ].join("\n"));
  fs.mkdirSync(path.join(directory, "themes"), { recursive: true });
  fs.symlinkSync(path.join(HOST_ROOT, "node_modules"), path.join(directory, "node_modules"), "dir");
  fs.symlinkSync(THEME_ROOT, path.join(directory, "themes", "stellar"), "dir");
}

function expectedOutputs(blueprint) {
  if (blueprint === "docs-reference") {
    return ["public/wiki/index.html", "public/wiki/docs-reference/index.html", "public/wiki/docs-reference/getting-started/index.html"];
  }
  return ["public/index.html"];
}

function assertBlueprintShell(directory, blueprint) {
  const relative = blueprint === "docs-reference"
    ? "public/wiki/docs-reference/index.html"
    : "public/index.html";
  const html = fs.readFileSync(path.join(directory, relative), "utf8");
  const has = marker => html.includes(marker);
  if (blueprint === "classic" && (!has('data-region="leftbar"') || has('data-region="topbar"'))) {
    throw new Error("classic: expected Sidebar-only navigation shell");
  }
  if (blueprint === "minimal-reading" && (!has('data-region="topbar"') || has('data-region="leftbar"'))) {
    throw new Error("minimal-reading: expected Topbar-only navigation shell");
  }
  if (blueprint === "docs-reference" && ["topbar", "sidebar", "context"].some(region => !has(`data-region="${region}"`))) {
    throw new Error("docs-reference: expected Topbar + Sidebar + Context shell");
  }
  if (blueprint === "light-and-shadow" && (!has('data-region="topbar"') || !has('class="post-list post"') || has('data-region="leftbar"'))) {
    throw new Error("light-and-shadow: expected Topbar + standard Feed without Sidebar");
  }
}

function main() {
  if (!fs.existsSync(HEXO)) throw new Error(`Hexo executable not found: ${HEXO}`);
  for (const blueprint of BLUEPRINTS) {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), `stellar-${blueprint}-`));
    try {
      writeSiteSkeleton(directory);
      run(directory, ["stellar", "init", "--blueprint", blueprint, "--non-interactive"]);
      const doctorOutput = run(directory, ["stellar", "doctor", "--format", "json", "--silent"]);
      const doctor = JSON.parse(doctorOutput);
      if (!doctor.ok) throw new Error(`${blueprint}: doctor failed`);
      run(directory, ["generate"]);
      for (const output of expectedOutputs(blueprint)) {
        if (!fs.existsSync(path.join(directory, output))) throw new Error(`${blueprint}: missing ${output}`);
      }
      assertBlueprintShell(directory, blueprint);
      process.stdout.write(`${blueprint}: init → doctor → generate passed\n`);
    } finally {
      fs.rmSync(directory, { recursive: true, force: true });
    }
  }
}

main();
